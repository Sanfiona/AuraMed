def tlumacz_chorobe(nazwa_ang):
    """Tłumaczy opis/nazwę choroby z angielskiego na polski."""
    return CHOROBY_PL.get(nazwa_ang, nazwa_ang)

def tlumacz_objaw(nazwa_ang):
    """Tłumaczy nazwę objawu z angielskiego na polski."""
    return OBJAWY_PL.get(nazwa_ang, nazwa_ang.replace('_', ' ').capitalize())

def tlumacz_diete(nazwa_ang):
    """Tłumaczy nazwę diety z angielskiego na polski."""
    return DIETY_PL.get(nazwa_ang, nazwa_ang)

def tlumacz_zalecenie(nazwa_ang):
    """Tłumaczy zalecenie z angielskiego na polski."""
    return ZALECENIA_PL.get(nazwa_ang, nazwa_ang)

def przygotuj_liste_objawow(feature_names):
    """
    Zwraca listę par (polska_nazwa, angielska_nazwa) posortowaną po polskiej nazwie.
    Użyj w multiselect jako opcje.
    """
    pary = [(tlumacz_objaw(name), name) for name in feature_names]
    return sorted(pary, key=lambda x: x[0])